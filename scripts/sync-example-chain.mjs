#!/usr/bin/env node
/**
 * Copies the recorded ManifestStore that @provenote/core's tests use into
 * apps/web/src/data/recorded-example.ts, so the home page can render a real
 * parsed chain above the fold.
 *
 * Why a copy rather than an import: the app should not reach into another
 * package's test directory, and the shape is load-bearing for the page's
 * first paint. Why a recorded object rather than a live parse on load: the
 * C2PA WebAssembly binary is 7.4 MB, and making every first-time visitor pay
 * that before they see anything is the opposite of a hero. The page runs the
 * SAME summarizeChain() over this object that the live Inspector runs over a
 * dropped file, and says on screen that it is a recorded example.
 *
 * Run: node scripts/sync-example-chain.mjs
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "packages/core/test/fixtures/recorded-validates.json");
const OUT = join(ROOT, "apps/web/src/data/recorded-example.ts");

const obj = JSON.parse(await readFile(SRC, "utf8"));

const banner = `/**
 * GENERATED by scripts/sync-example-chain.mjs — do not hand-edit.
 *
 * A ManifestStore recorded VERBATIM from a real browser run of
 * @contentauth/c2pa-web against a real signed JPEG (its own _provenance
 * field records when and how). The home page runs the same
 * summarizeChain() transformer over it that the live Inspector runs over a
 * file you drop, and labels the result as a recorded example rather than
 * as a live read.
 */
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, `${banner}export const RECORDED_EXAMPLE = ${JSON.stringify(obj, null, 2)} as const;\n`);
console.log(`sync-example-chain: ${SRC} -> ${OUT}`);
